# -*- coding: utf-8 -*-
"""Обновить Defroster без капли и сгенерировать image_Inj_Drop.cpp."""
import struct
import zlib
from pathlib import Path

ROOT = Path(r"d:\ST\Defrost\TouchGFX")
ASSETS = ROOT / "assets" / "images"
GEN = ROOT / "generated" / "images" / "src"


def load_png(path: Path):
    data = path.read_bytes()
    i = 8
    idats = b""
    w = h = None
    while i < len(data):
        ln = struct.unpack(">I", data[i : i + 4])[0]
        typ = data[i + 4 : i + 8]
        chunk = data[i + 8 : i + 8 + ln]
        i += 12 + ln
        if typ == b"IHDR":
            w, h = struct.unpack(">II", chunk[:8])
        if typ == b"IDAT":
            idats += chunk
        if typ == b"IEND":
            break
    raw = zlib.decompress(idats)
    bpp = 4
    stride = w * bpp
    prev = bytearray(stride)
    o = 0
    rows = []
    for _y in range(h):
        f = raw[o]
        o += 1
        row = bytearray(raw[o : o + stride])
        o += stride
        if f == 1:
            for x in range(stride):
                a = row[x - bpp] if x >= bpp else 0
                row[x] = (row[x] + a) & 255
        elif f == 2:
            for x in range(stride):
                row[x] = (row[x] + prev[x]) & 255
        elif f == 3:
            for x in range(stride):
                a = row[x - bpp] if x >= bpp else 0
                row[x] = (row[x] + ((a + prev[x]) >> 1)) & 255
        elif f == 4:

            def paeth(a, b, c):
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                if pa <= pb and pa <= pc:
                    return a
                if pb <= pc:
                    return b
                return c

            for x in range(stride):
                a = row[x - bpp] if x >= bpp else 0
                b = prev[x]
                c = prev[x - bpp] if x >= bpp else 0
                row[x] = (row[x] + paeth(a, b, c)) & 255
        rows.append(row)
        prev = bytearray(row)
    return w, h, rows


def emit_cpp(var: str, w: int, h: int, rows, out_path: Path):
    pixels = []
    for y in range(h):
        for x in range(w):
            r, g, b, a = rows[y][x * 4 : x * 4 + 4]
            pixels.extend([b, g, r, a])
    lines = [
        "// 4.26.1 manual FARGB8888 ExtFlashSection",
        "// Generated by tools/gen_inj_drop_bitmaps.py",
        "",
        "#include <touchgfx/hal/Config.hpp>",
        "",
        'LOCATION_PRAGMA("ExtFlashSection")',
        f"KEEP extern const unsigned char {var}[] LOCATION_ATTRIBUTE(\"ExtFlashSection\") = {{ // {w}x{h} ARGB8888 pixels.",
    ]
    for i in range(0, len(pixels), 12):
        chunk = pixels[i : i + 12]
        lines.append("    " + ", ".join(f"0x{p:02x}" for p in chunk) + ",")
    lines.append("};")
    lines.append("")
    out_path.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {out_path} ({len(pixels)} bytes pixel data)")


def main():
    bak = ASSETS / "Defroster_with_drop_backup.png"
    cur = ASSETS / "Defroster.png"
    src = bak if bak.exists() else cur
    w, h, rows = load_png(src)

    # Капля в исходнике: bbox (85..100, 85..111)
    x0, y0, x1, y1 = 85, 85, 100, 111
    drop_w, drop_h = x1 - x0 + 1, y1 - y0 + 1
    drop_rows = []
    for y in range(y0, y1 + 1):
        row = bytearray(drop_w * 4)
        for x in range(x0, x1 + 1):
            r, g, b, a = rows[y][x * 4 : x * 4 + 4]
            if a >= 128 and r + g + b >= 40:
                i = (x - x0) * 4
                row[i : i + 4] = bytes([r, g, b, a])
                # стереть из Defroster
                rows[y][x * 4 : x * 4 + 4] = bytes([0, 0, 0, 0])
        drop_rows.append(row)

    emit_cpp("image_defroster", w, h, rows, GEN / "image_Defroster.cpp")
    emit_cpp("image_inj_drop", drop_w, drop_h, drop_rows, GEN / "image_Inj_Drop.cpp")
    print(f"drop {drop_w}x{drop_h}")


if __name__ == "__main__":
    main()
