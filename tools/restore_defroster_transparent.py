# -*- coding: utf-8 -*-
"""Восстановить Defroster.png с прозрачностью из backup и убрать центральную каплю."""
import struct
import zlib
from pathlib import Path

BACKUP = Path(r"d:\ST\Defrost\tools\assets_backup\Defroster_with_drop_backup.png")
OUT = Path(r"d:\ST\Defrost\TouchGFX\assets\images\Defroster.png")
GEN = Path(r"d:\ST\Defrost\TouchGFX\generated\images\src\image_Defroster.cpp")


def load_png(path: Path):
    data = path.read_bytes()
    i = 8
    idats = b""
    w = h = None
    while i < len(data):
        ln = struct.unpack(">I", data[i : i + 4])[0]
        typ = data[i + 4 : i + 8]
        chunk = data[i + 8 : i + 8 + ln]
        i += 12 + ln
        if typ == b"IHDR":
            w, h = struct.unpack(">II", chunk[:8])
        if typ == b"IDAT":
            idats += chunk
    raw = zlib.decompress(idats)
    bpp = 4
    stride = w * bpp
    prev = bytearray(stride)
    o = 0
    rows = []
    for _y in range(h):
        f = raw[o]
        o += 1
        row = bytearray(raw[o : o + stride])
        o += stride
        if f == 1:
            for x in range(stride):
                a = row[x - bpp] if x >= bpp else 0
                row[x] = (row[x] + a) & 255
        elif f == 2:
            for x in range(stride):
                row[x] = (row[x] + prev[x]) & 255
        elif f == 3:
            for x in range(stride):
                a = row[x - bpp] if x >= bpp else 0
                row[x] = (row[x] + ((a + prev[x]) >> 1)) & 255
        elif f == 4:

            def paeth(a, b, c):
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                if pa <= pb and pa <= pc:
                    return a
                if pb <= pc:
                    return b
                return c

            for x in range(stride):
                a = row[x - bpp] if x >= bpp else 0
                b = prev[x]
                c = prev[x - bpp] if x >= bpp else 0
                row[x] = (row[x] + paeth(a, b, c)) & 255
        rows.append(row)
        prev = bytearray(row)
    return w, h, rows


def save_png(path: Path, w: int, h: int, rows):
    raw = bytearray()
    for y in range(h):
        raw.append(0)
        raw.extend(rows[y])
    compressed = zlib.compress(bytes(raw), 9)

    def chunk(typ, data):
        return struct.pack(">I", len(data)) + typ + data + struct.pack(
            ">I", zlib.crc32(typ + data) & 0xFFFFFFFF
        )

    ihdr = struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0)
    path.write_bytes(
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", ihdr)
        + chunk(b"IDAT", compressed)
        + chunk(b"IEND", b"")
    )


def emit_cpp(w: int, h: int, rows, out_path: Path):
    pixels = []
    for y in range(h):
        for x in range(w):
            r, g, b, a = rows[y][x * 4 : x * 4 + 4]
            pixels.extend([b, g, r, a])
    lines = [
        "// 4.26.1 restored transparent Defroster (no center drop)",
        "// Generated by tools/restore_defroster_transparent.py",
        "",
        "#include <touchgfx/hal/Config.hpp>",
        "",
        'LOCATION_PRAGMA("ExtFlashSection")',
        f'KEEP extern const unsigned char image_defroster[] LOCATION_ATTRIBUTE("ExtFlashSection") = {{ // {w}x{h} ARGB8888 pixels.',
    ]
    for i in range(0, len(pixels), 12):
        chunk = pixels[i : i + 12]
        lines.append("    " + ", ".join(f"0x{p:02x}" for p in chunk) + ",")
    lines.append("};")
    lines.append("")
    out_path.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def main():
    w, h, rows = load_png(BACKUP)
    erased = 0
    # Центральная капля (bbox 85..100, 85..111)
    for y in range(85, 112):
        for x in range(85, 101):
            r, g, b, a = rows[y][x * 4 : x * 4 + 4]
            if a >= 128 and r + g + b >= 40:
                rows[y][x * 4 : x * 4 + 4] = bytes([0, 0, 0, 0])
                erased += 1
    save_png(OUT, w, h, rows)
    emit_cpp(w, h, rows, GEN)
    a0 = sum(1 for y in range(h) for x in range(w) if rows[y][x * 4 + 3] == 0)
    print(f"OK: {OUT}")
    print(f"  erased drop pixels: {erased}")
    print(f"  transparent pixels: {a0}")
    print(f"  regenerated: {GEN}")


if __name__ == "__main__":
    main()
